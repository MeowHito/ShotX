import { SHARE_SLUG_MAX_LENGTH, SHARE_TOKEN_LENGTH } from '@shotx/shared';
import { sql } from 'drizzle-orm';
import {
  boolean,
  check,
  foreignKey,
  index,
  pgTable,
  real,
  text,
  unique,
  uniqueIndex,
  uuid,
} from 'drizzle-orm/pg-core';
import { users } from './accounts';
import { createdAt, id, timestamptz } from './columns';
import { shareDesigns } from './designs';
import { files, folders } from './drive';
import {
  consentPurpose,
  downloadSize,
  faceFeedbackVerdict,
  shareMode,
  shareTargetType,
  uiLocale,
} from './enums';

const slugMaxLength = sql.raw(String(SHARE_SLUG_MAX_LENGTH));
/**
 * Any ASCII character other than [0-9a-z-] (PostgreSQL ARE escapes, kept literal by String.raw):
 * locale-independent, unlike [[:punct:]], which some locales give to Thai combining marks.
 */
const asciiOtherThanSlug = sql.raw(String.raw`'[\x01-\x2c\x2e\x2f\x3a-\x60\x7b-\x7f]'`);
// Slugs are never token-shaped (isShareSlug), so a ref is one or the other.
const tokenShaped = sql.raw(`'^[0-9a-z]{${SHARE_TOKEN_LENGTH}}$'`);

/**
 * Share links, `/s/{token}`. The token is 128 random bits in base62 (~22 characters).
 *
 * `slug` (ADR 0011, migration 0012): the readable ref, `/s/{slug}`, generated by the api from the
 * target's name (slugifyEventName, shareSlugCandidate in @shotx/shared), canonical (NFC,
 * lowercase), unique over every share ever made (revoked included; never reused) and never
 * changed. Lookups canonicalize the ref the same way (parseShareRef), which makes them
 * case-insensitive. Nullable only so the previous api release can still insert during the deploy;
 * migration 0012 backfilled every existing share. Follow-up once the api always writes it:
 * backfill the stragglers and SET NOT NULL. `shares_slug_valid` checks what SQL can without
 * locale-dependent character classes: length, no ASCII other than [0-9a-z-] (so no uppercase,
 * space, `/`, `%`, `.`), no leading, trailing or double `-`, and not token-shaped; the Unicode
 * rules are isShareSlug's.
 *
 * The target is a file (`target_file_id`) or a folder (`target_folder_id`) of the share's owner:
 * each has a foreign key on (target, owner_id), so a share can never point at another
 * photographer's file or folder. Exactly one is set, and `target_type` says which (it is kept,
 * although derivable, because the data model and API use it; the CHECKs keep the three columns
 * consistent). Files and folders with shares can't be deleted (ON DELETE RESTRICT): purge removes
 * their shares (and the shares' consents) first.
 */
export const shares = pgTable(
  'shares',
  {
    id: id(),
    ownerId: uuid('owner_id')
      .notNull()
      .references(() => users.id),
    targetType: shareTargetType('target_type').notNull(),
    /** Set exactly when `target_type` is `file`. */
    targetFileId: uuid('target_file_id'),
    /** Set exactly when `target_type` is `folder`. */
    targetFolderId: uuid('target_folder_id'),
    token: text('token').notNull(),
    slug: text('slug'),
    mode: shareMode('mode').notNull().default('gallery'),
    allowDownload: boolean('allow_download').notNull().default(true),
    downloadSize: downloadSize('download_size').notNull().default('web'),
    requireLogin: boolean('require_login').notNull().default(false),
    /** argon2id. */
    passwordHash: text('password_hash'),
    expiresAt: timestamptz('expires_at'),
    isActive: boolean('is_active').notNull().default(true),
    /**
     * Set while the owner has unpublished the share ("ปิดไม่เผยแพร่", ADR 0016, migration 0014):
     * public routes answer SHARE_EXPIRED `paused`; clearing it publishes the same link again.
     * Unlike `is_active = false` (revoked, final), pausing is reversible.
     */
    pausedAt: timestamptz('paused_at'),
    createdAt: createdAt(),
    /**
     * The share page design (ADR 0013, migration 0013); null: the owner's default design at view
     * time, else the plain layout. The foreign key on (design_id, owner_id) keeps it the owner's
     * design and clears it when the design is deleted (ON DELETE SET NULL of design_id only,
     * hand-written in the migration as for `folders.cover_file_id`).
     */
    designId: uuid('design_id'),
  },
  (t) => [
    unique('shares_token_unique').on(t.token),
    unique('shares_id_owner_unique').on(t.id, t.ownerId),
    foreignKey({
      name: 'shares_target_file_same_owner_fk',
      columns: [t.targetFileId, t.ownerId],
      foreignColumns: [files.id, files.ownerId],
    }).onDelete('restrict'),
    foreignKey({
      name: 'shares_target_folder_same_owner_fk',
      columns: [t.targetFolderId, t.ownerId],
      foreignColumns: [folders.id, folders.ownerId],
    }).onDelete('restrict'),
    // GET /shares: the owner's shares, newest first (ids are uuidv7).
    index('shares_owner_list_idx').on(t.ownerId, t.id),
    index('shares_target_file_idx')
      .on(t.targetFileId, t.ownerId)
      .where(sql`${t.targetFileId} IS NOT NULL`),
    index('shares_target_folder_idx')
      .on(t.targetFolderId, t.ownerId)
      .where(sql`${t.targetFolderId} IS NOT NULL`),
    check('shares_one_target', sql`num_nonnulls(${t.targetFileId}, ${t.targetFolderId}) = 1`),
    check(
      'shares_target_matches_type',
      sql`(${t.targetType} = 'file') = (${t.targetFileId} IS NOT NULL) AND (${t.targetType} = 'folder') = (${t.targetFolderId} IS NOT NULL)`,
    ),
    check('shares_token_base62', sql`${t.token} ~ '^[0-9A-Za-z]{16,64}$'`),
    // Migration 0013 (ADR 0013).
    foreignKey({
      name: 'shares_design_same_owner_fk',
      columns: [t.designId, t.ownerId],
      foreignColumns: [shareDesigns.id, shareDesigns.ownerId],
    }).onDelete('set null'),
    // The FK's ON DELETE when a design is deleted.
    index('shares_design_idx')
      .on(t.designId, t.ownerId)
      .where(sql`${t.designId} IS NOT NULL`),
    // Migration 0012.
    unique('shares_slug_unique').on(t.slug),
    check(
      'shares_slug_valid',
      sql`${t.slug} IS NULL OR (char_length(${t.slug}) BETWEEN 1 AND ${slugMaxLength} AND ${t.slug} !~ ${asciiOtherThanSlug} AND ${t.slug} !~ '(^-|-$|--)' AND ${t.slug} !~ ${tokenShaped})`,
    ),
  ],
);

/**
 * Consent per share, purpose and viewer (logged in) or anonymous session (`anon_id` cookie), for
 * one policy version. A scan needs a row of its purpose for the current version that is not
 * withdrawn: `face_search` before a face search, `face_deletion` before "ขอลบใบหน้าของฉัน"
 * (migration 0004; existing rows are `face_search`). See CONSENT_PURPOSE_GATES in @shotx/shared.
 * `ip_hash` is a keyed hash, never the address (`v1:` + HMAC, see IP_HASH_VERSION).
 *
 * Exactly one of `viewer_id` and `anon_id` is set (viewerColumns in @shotx/shared). At most one
 * current (not withdrawn) consent exists per share, viewer or session, purpose and version, so
 * giving consent is an idempotent upsert: `INSERT ... ON CONFLICT DO NOTHING` on the partial
 * unique index, then select. Withdrawal sets `withdrawn_at` on every current row of the viewer or
 * session for the share (every purpose); a later consent inserts a new row, so the history stays.
 *
 * `locale` (ADR 0011, migration 0012): the language the consent text was shown in. Rows from
 * before 0012 are `th` (the only language then). The Thai text is the legal reference; the
 * idempotent upsert keeps the first row's locale.
 */
export const consents = pgTable(
  'consents',
  {
    id: id(),
    shareId: uuid('share_id')
      .notNull()
      .references(() => shares.id),
    viewerId: uuid('viewer_id').references(() => users.id),
    anonId: uuid('anon_id'),
    purpose: consentPurpose('purpose').notNull().default('face_search'),
    policyVersion: text('policy_version').notNull(),
    locale: uiLocale('locale').notNull().default('th'),
    ipHash: text('ip_hash').notNull(),
    acceptedAt: timestamptz('accepted_at').notNull().defaultNow(),
    withdrawnAt: timestamptz('withdrawn_at'),
  },
  (t) => [
    index('consents_share_viewer_idx').on(t.shareId, t.viewerId),
    index('consents_share_anon_idx').on(t.shareId, t.anonId),
    uniqueIndex('consents_current_viewer_unique')
      .on(t.shareId, t.viewerId, t.purpose, t.policyVersion)
      .where(sql`${t.withdrawnAt} IS NULL AND ${t.viewerId} IS NOT NULL`),
    uniqueIndex('consents_current_anon_unique')
      .on(t.shareId, t.anonId, t.purpose, t.policyVersion)
      .where(sql`${t.withdrawnAt} IS NULL AND ${t.anonId} IS NOT NULL`),
    check('consents_viewer_or_anon', sql`num_nonnulls(${t.viewerId}, ${t.anonId}) = 1`),
    check(
      'consents_withdrawn_after_accepted',
      sql`${t.withdrawnAt} IS NULL OR ${t.withdrawnAt} >= ${t.acceptedAt}`,
    ),
    check('consents_policy_version_not_empty', sql`length(${t.policyVersion}) > 0`),
  ],
);

/**
 * "ไม่ใช่ฉัน" feedback for threshold tuning. No biometrics and no viewer identity. `similarity` is
 * the score the API stored in the viewer's face-search result (never sent by the client).
 */
export const faceFeedback = pgTable(
  'face_feedback',
  {
    id: id(),
    shareId: uuid('share_id')
      .notNull()
      .references(() => shares.id, { onDelete: 'cascade' }),
    fileId: uuid('file_id')
      .notNull()
      .references(() => files.id, { onDelete: 'cascade' }),
    similarity: real('similarity').notNull(),
    verdict: faceFeedbackVerdict('verdict').notNull().default('not_me'),
    createdAt: createdAt(),
  },
  (t) => [
    index('face_feedback_share_idx').on(t.shareId),
    index('face_feedback_file_idx').on(t.fileId),
    // Tuning exports and the "ไม่ใช่ฉัน" rate read by time.
    index('face_feedback_created_idx').on(t.createdAt),
    check('face_feedback_similarity_range', sql`${t.similarity} BETWEEN 0 AND 100`),
  ],
);
