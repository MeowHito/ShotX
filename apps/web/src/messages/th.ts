/**
 * Consent texts, one per CONSENT_PURPOSES purpose and CONSENT_POLICY_VERSIONS version. A version's
 * text never changes once released: new wording means a new version in @shotx/shared. The
 * face-search text states how long results are kept (`{ttl}`, from the API's
 * SHARE_FACE_ONLY_GRANT_TTL_SECONDS in share meta). The DPO or legal team approves each version
 * before launch.
 */
interface ConsentPolicyText {
  title: string;
  /** Every version but the short face-search text of 2026-11-11b. */
  intro?: string;
  /** The visible points, in this order; a version shows those it has. */
  points: {
    purpose: string;
    noStorage: string;
    results: string;
    processor: string;
    /**
     * Since 2026-11-11: the face data leaves Thailand (PDPA section 28), where it goes and how it
     * is protected. Shown after `processor` when the version has it.
     */
    transfer?: string;
    withdraw?: string;
  };
  /**
   * Since 2026-11-11b (face search): the full legal text behind "อ่านรายละเอียด" (collapsed by
   * default). The visible points plus these are the version's whole text.
   */
  details?: {
    sensitive: string;
    selfie: string;
    index: string;
    processor: string;
    transfer: string;
    backups: string;
    rights: string;
    contact: string;
  };
  checkbox: string;
}

